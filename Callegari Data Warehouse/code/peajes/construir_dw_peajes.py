def cargar_tramos(con, base, sk_lugar, sk_seg, hoy):
    """dim_tramo SCD2: una versión nueva si cambia el texto del tramo (cambia la ruta); km e isactive se corrigen (SCD1)."""
    tr = leer(base / "tramos_peajes" / "peaje_por_tramo.csv", dtype=str).fillna("")
    actuales = {r[0]: r[1:] for r in con.execute(
        "SELECT sit_stretch_id, sk_tramo, texto_tramo, vigente_desde FROM dim_tramo WHERE es_actual='S'")}
    nuevas = 0
    for _, r in tr.iterrows():
        sid = entero_id(r["sit_stretch_id"])
        partes = [clave(p) for p in r["tramo"].split("/") if p.strip()]
        valores = dict(sk_lugar_origen=sk_lugar.get(partes[0]) if partes else None,
                       sk_lugar_destino=sk_lugar.get(partes[-1]) if partes else None, n_puntos=len(partes),
                       km_erp=numero(r["kilometers"]), km_ruta_calculada=numero(r["km_ruta"]),
                       es_recorrido="S" if len(partes) > 2 else "N", isactive=r["isactive"], estado_deteccion=r["estado"])
        previo = actuales.get(sid)
        if previo and previo[1] == r["tramo"]:
            sk = previo[0]
            con.execute("UPDATE dim_tramo SET " + ", ".join(f"{k}=?" for k in valores) + " WHERE sk_tramo=?",
                        (*valores.values(), sk))
        else:
            desde = INICIO
            if previo:                                           # el texto cambió: se cierra la versión anterior
                con.execute("UPDATE dim_tramo SET vigente_hasta=?, es_actual='N' WHERE sk_tramo=?", (dia_antes(hoy), previo[0]))
                desde = hoy
            cur = con.execute("INSERT INTO dim_tramo (sit_stretch_id, texto_tramo, " + ", ".join(valores) +
                              ", vigente_desde, vigente_hasta, es_actual) VALUES (?,?," + ",".join("?" * len(valores)) +
                              ",?,?,'S') RETURNING sk_tramo", (sid, r["tramo"], *valores.values(), desde, FIN))
            sk, nuevas = cur.fetchone()[0], nuevas + 1
        con.execute("DELETE FROM puente_tramo_segmento WHERE sk_tramo=?", (sk,))
        for i, (a, b) in enumerate(zip(partes, partes[1:]), start=1):
            if (a, b) in sk_seg:
                con.execute("INSERT INTO puente_tramo_segmento VALUES (?,?,?)", (sk, sk_seg[(a, b)], i))
    return nuevas


def cargar_documentos(con, base):
    docs = leer(base / "peajes_datos" / "documentos.csv", dtype=str)
