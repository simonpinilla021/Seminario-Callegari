def calcular_referencial(con):
    """fact_peaje_referencial_tramo: para cada tramo y cada periodo en que no cambia ni una tarifa ni una plaza de su
    recorrido, el peaje base (regla de parametro_peaje) y el máximo (la condición más cara que aplica a la flota)."""
    par = parametros(con)
    pref_hor = par["horario_base"].split("|")
    pref_mod = par["modalidad_base"].split("|")
    pref_cat = par["categoria_flota"].split("|")
    tar = con.df("""SELECT f.id_plaza, f.vigente_desde::text AS vigente_desde, f.vigente_hasta::text AS vigente_hasta,
                           f.tarifa_clp, f.origen_tarifa, c.categoria_vehicular AS categoria, c.horario, c.modalidad
                    FROM fact_tarifa_peaje f JOIN dim_condicion_tarifa c USING (sk_condicion)""")
    puente = con.df("""SELECT ts.sk_tramo, ts.orden AS orden_seg, sp.sk_segmento, sp.orden, sp.id_plaza,
                              sp.vigente_desde::text AS vigente_desde, sp.vigente_hasta::text AS vigente_hasta
                       FROM puente_tramo_segmento ts JOIN puente_segmento_plaza sp USING (sk_segmento)""")
    plaza = con.df("SELECT id_plaza, concesion, cobro_por_recorrido FROM dim_plaza_peaje WHERE es_actual='S' "
                   "OR sk_plaza IN (SELECT MAX(sk_plaza) FROM dim_plaza_peaje GROUP BY id_plaza)")
    recorrido = dict(zip(plaza["id_plaza"], [clave(c) if f == "S" else "" for c, f in zip(plaza["concesion"],
                                                                                          plaza["cobro_por_recorrido"])]))
    tar_por_plaza = {k: g for k, g in tar.groupby("id_plaza")}
    memo = {}

    def valores(idp, fecha):
        """(base, máximo) de una plaza en una fecha; None si no tiene tarifa vigente."""
        if (idp, fecha) in memo:
            return memo[(idp, fecha)]
        g = tar_por_plaza.get(idp)
        res = (None, None, None)
        if g is not None:
            g = g[(g["vigente_desde"] <= fecha) & (fecha <= g["vigente_hasta"])]
            if (g["origen_tarifa"] == "manual").any():
                g = g[g["origen_tarifa"] == "manual"]
            if len(g):
                g = g[g["vigente_desde"] == g["vigente_desde"].max()]
                m = g
                for p in pref_cat:                                  # máximo: solo la categoría de la flota
                    if (m["categoria"] == p).any():
                        m = m[m["categoria"] == p]
                        break
                b = g
                for col, prefs in (("horario", pref_hor), ("modalidad", pref_mod)):
                    for p in prefs:
                        if (b[col] == p).any():
                            b = b[b[col] == p]
                            break
                for p in pref_cat:
                    if (b["categoria"] == p).any():
                        b = b[b["categoria"] == p]
                        break
                fb = b.loc[b["tarifa_clp"].idxmax()]
                res = (float(b["tarifa_clp"].max()), float(m["tarifa_clp"].max()),
                       (fb["categoria"], fb["horario"], fb["modalidad"]))
        memo[(idp, fecha)] = res
        return res

    def total(filas, fecha):
        """Suma del tramo en una fecha: en concesiones que cobran por recorrido, una vez por segmento (la mayor).
        Devuelve también el detalle por plaza (fact_peaje_referencial_plaza), que suma exactamente lo mismo."""
        base = maxi = 0.0
        n = sin = 0
        grupos = {}
        det = []
        for r in sorted(filas, key=lambda x: (x.orden_seg, x.orden)):
            if not (r.vigente_desde <= fecha <= r.vigente_hasta):
                continue
            n += 1
            b, m, cond = valores(r.id_plaza, fecha)
            fila = [int(r.orden_seg), int(r.sk_segmento), int(r.orden), r.id_plaza, b, m, *(cond or (None, None, None)),
                    "N", 0.0, 0.0, "sin tarifa vigente"]
            det.append(fila)
            if b is None:
                sin += 1
                continue
            g = recorrido.get(r.id_plaza, "")
            if g:
                k = (r.sk_segmento, g)
                grupos.setdefault(k, []).append(fila)
            else:
                base, maxi = base + b, maxi + m
                fila[9:13] = ["S", b, m, "cobrada"]
        for grupo in grupos.values():                       # cobro por recorrido: se cobra la mayor, una vez
            fb = max(grupo, key=lambda x: x[4])
            fm = max(grupo, key=lambda x: x[5])
            base, maxi = base + fb[4], maxi + fm[5]
            for x in grupo:
                x[9:13] = ["N", 0.0, 0.0, "cobro por recorrido: se cobra otra plaza de la concesión"]
            fb[9], fb[10], fb[12] = "S", fb[4], "cobrada (cobro por recorrido, la mayor)"
            fm[11] = fm[5]
            if fm is not fb:
                fm[12] = "máximo por recorrido (el base se cobra en otra plaza)"
        return base, maxi, n, sin, det

    cortes_tar = {}
    for idp, g in tar_por_plaza.items():
        cortes_tar[idp] = set(g["vigente_desde"]) | {dia_despues(h) for h in g["vigente_hasta"]}
    con.execute("DELETE FROM fact_peaje_referencial_tramo")
    con.execute("DELETE FROM fact_peaje_referencial_plaza")
    tramos = [r[0] for r in con.execute("SELECT sk_tramo FROM dim_tramo")]
    por_tramo = {k: list(g.itertuples(index=False)) for k, g in puente.groupby("sk_tramo")}
    con_seg = {r[0] for r in con.execute("SELECT DISTINCT sk_tramo FROM puente_tramo_segmento")}
    filas_salida, filas_detalle = [], []
    for sk in tramos:
        filas = por_tramo.get(sk, [])
        if sk not in con_seg:
            filas_salida.append((sk, INICIO, FIN, None, None, 0, 0, "no calculado"))
            continue
        cortes = {INICIO}
        for r in filas:
            cortes |= {r.vigente_desde, dia_despues(r.vigente_hasta)} | cortes_tar.get(r.id_plaza, set())
        cortes = sorted(c for c in cortes if c < FIN)
        periodos, periodos_det = [], []
        for i, c in enumerate(cortes):
            hasta = dia_antes(cortes[i + 1]) if i + 1 < len(cortes) else FIN
            if hasta < c:
                continue
            b, m, n, sin, det = total(filas, c)
            clave_det = [tuple(x) for x in det]
            if periodos_det and periodos_det[-1][2] == clave_det:  # el detalle se junta con su propio criterio
                periodos_det[-1][1] = hasta
            else:
                periodos_det.append([c, hasta, clave_det])
            if not n:
                estado = "sin plazas"
            elif sin == n:
                estado = "sin tarifas"
            elif sin:
                estado = "parcial"
            else:
                estado = "completo"
            val = (round(b, 2), round(m, 2), n, sin, estado)
            if periodos and periodos[-1][3:] == val:            # periodos seguidos con el mismo resultado se juntan
                periodos[-1][2] = hasta
            else:
                periodos.append([sk, c, hasta, *val])
        for p in periodos:
            if p[7] == "sin tarifas":
                p[3] = p[4] = None
            filas_salida.append(tuple(p))
        for desde, hasta, det in periodos_det:
            for x in det:
                filas_detalle.append((sk, desde, hasta, *x[:9], x[9], round(x[10], 2), round(x[11], 2), x[12]))
    con.copiar("fact_peaje_referencial_tramo", ["sk_tramo", "vigente_desde", "vigente_hasta", "peaje_base", "peaje_maximo",
                                                "cantidad_plazas", "plazas_sin_tarifa", "estado"], filas_salida)
    con.copiar("fact_peaje_referencial_plaza", ["sk_tramo", "vigente_desde", "vigente_hasta", "orden_segmento",
                                                "sk_segmento", "orden_en_segmento", "id_plaza", "tarifa_base_plaza",
                                                "tarifa_maxima_plaza", "categoria_base", "horario_base", "modalidad_base",
                                                "cobrada", "peaje_base", "peaje_maximo", "motivo"], filas_detalle)
    return len(filas_salida)


def cargar_viajes(con, base, archivo):
    ruta = Path(archivo) if archivo else db.ruta_config("fuentes", "erp") / "adempiere_sit_pbix_travelvta_v.parquet"
    columnas = ["c_orderline_id", "sit_roadmap_id", "sit_stretch_id", "datepromised", "isreturn"]
    try:
        v = pd.read_csv(ruta, usecols=columnas) if ruta.suffix.lower() == ".csv" else pd.read_parquet(ruta, columns=columnas)
    except Exception as e:                                      # noqa: BLE001
        print(f"   viajes: no se pudo leer {ruta} ({e.__class__.__name__}: {e}). Se omite fact_viaje_peaje.")
        return None
    v = v.drop_duplicates("c_orderline_id")
    v["fecha"] = pd.to_datetime(v["datepromised"], errors="coerce").dt.strftime("%Y-%m-%d")
    con.execute("DELETE FROM fact_viaje_peaje")
    con.execute("DROP TABLE IF EXISTS tmp_viaje")
    con.execute("CREATE TEMP TABLE tmp_viaje (nro_viaje BIGINT, nro_hoja_ruta BIGINT, sit_stretch_id BIGINT, fecha DATE, "
                "es_retorno TEXT)")
    con.copiar_df("tmp_viaje", pd.DataFrame({
        "nro_viaje": v["c_orderline_id"].astype("Int64"), "nro_hoja_ruta": v["sit_roadmap_id"].astype("Int64"),
        "sit_stretch_id": v["sit_stretch_id"].astype("Int64"), "fecha": v["fecha"], "es_retorno": v["isreturn"].fillna("")}))
    con.execute("""
        INSERT INTO fact_viaje_peaje (nro_viaje, nro_hoja_ruta, sk_tramo, sk_fecha_inicio, es_retorno, peaje_referencial,
                                peaje_referencial_maximo, estado_peaje)
        SELECT v.nro_viaje, v.nro_hoja_ruta, t.sk_tramo, to_char(v.fecha, 'YYYYMMDD')::int, v.es_retorno,
               r.peaje_base, r.peaje_maximo,
               CASE WHEN t.sk_tramo IS NULL THEN 'tramo no encontrado'
                    WHEN r.sk_tramo IS NULL THEN 'sin periodo'
                    WHEN r.peaje_base IS NULL THEN 'sin tarifa a la fecha'
                    ELSE r.estado END
        FROM tmp_viaje v
        LEFT JOIN dim_tramo t ON t.sit_stretch_id = v.sit_stretch_id AND v.fecha BETWEEN t.vigente_desde AND t.vigente_hasta
        LEFT JOIN fact_peaje_referencial_tramo r ON r.sk_tramo = t.sk_tramo
             AND v.fecha BETWEEN r.vigente_desde AND r.vigente_hasta""")
    con.execute("DROP TABLE tmp_viaje")
    return dict(con.execute("SELECT estado_peaje, COUNT(*) FROM fact_viaje_peaje GROUP BY estado_peaje"))


def plantillas(carpeta):
    carpeta.mkdir(exist_ok=True)
    p = carpeta / "tarifas_manual.csv"
