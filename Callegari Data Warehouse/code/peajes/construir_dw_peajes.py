# ------------------------------------------------------------------------------------------------ utilidades
def sin_tildes(texto):
    return unicodedata.normalize("NFKD", str(texto)).encode("ascii", "ignore").decode()


def clave(texto):
    """La misma normalización de ciudades_tramos.py y peajes_por_tramo.py: 'Copiapó (Los Loros)' -> 'COPIAPO LOS LOROS'."""
    t = re.sub(r"[^A-Z0-9 ]", " ", sin_tildes(texto).upper())
    return re.sub(r"\s+", " ", t).strip()


def clave_plaza(concesion, nombre, posicion):
    return f"{clave(concesion)} | {clave(nombre)} | {clave(posicion)}"


try:                                     # el mismo reconocimiento de códigos de pórtico (PA15, P1.3) que usa el detector
    from peajes_por_tramo import codigo_portico
except Exception:                        # noqa: BLE001
    def codigo_portico(nombre):
        m = re.match(r"\s*(P[A-Z]?\s?\d+(?:[.,]\d+)?)\b", sin_tildes(nombre).upper())
        return (m.group(1).replace(" ", "").replace(",", "."), "") if m else ("", "")


def texto(v):
    return "" if v is None or (isinstance(v, float) and math.isnan(v)) else str(v).strip()


def numero(v):
    try:
        x = float(str(v).replace(",", "."))
        return None if math.isnan(x) else x
    except (TypeError, ValueError):
        return None


def entero_id(v):
    x = numero(v)
    return int(x) if x is not None else None


def leer(ruta, **kw):
    ruta = Path(ruta)
    if not ruta.exists():
        return None
    return pd.read_csv(ruta, encoding="utf-8-sig", **kw)


def dia_antes(fecha):
    return (date.fromisoformat(fecha) - timedelta(days=1)).isoformat()


def dia_despues(fecha):
    return FIN if fecha >= FIN else (date.fromisoformat(fecha) + timedelta(days=1)).isoformat()


def sk_fecha(fecha):
    return int(fecha.replace("-", "")) if fecha else None


