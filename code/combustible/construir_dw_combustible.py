def controles_costo(con):
    """Cuadraturas de la valorización (Modelo dimensional §12, prueba 2 ampliada a pesos)."""
    q = lambda sql: con.execute(sql).fetchone()
    c = {}
    c["cargas_sin_precio_litros"], c["cargas_sin_precio_n"] = q(
        "SELECT COALESCE(SUM(litros),0), COUNT(*) FROM fact_carga_combustible WHERE monto IS NULL")
    lb, lc = q("SELECT SUM(b.litros), (SELECT SUM(litros) FROM fact_carga_combustible WHERE bloque IS NOT NULL) "
               "FROM fact_bloque_combustible b")
    c["litros_bloques_vs_cargas"] = round((lb or 0) - (lc or 0), 1)
    cb, cp = q("SELECT (SELECT SUM(costo_combustible) FROM fact_bloque_combustible b WHERE EXISTS "
               "(SELECT 1 FROM puente_viaje_bloque p WHERE p.equipo_id=b.equipo_id AND p.bloque=b.bloque)), "
               "(SELECT SUM(costo_asignado) FROM puente_viaje_bloque)")
    c["costo_bloques_con_viajes_vs_puente"] = round((cb or 0) - (cp or 0), 0)
    cv, cp2 = q("SELECT (SELECT SUM(costo_bloque) FROM fact_viaje_combustible), (SELECT SUM(costo_asignado) FROM puente_viaje_bloque)")
    c["costo_viajes_desde_bloques_vs_puente"] = round((cv or 0) - (cp2 or 0), 0)
    lp, lv = q("SELECT (SELECT SUM(litros_asignados) FROM puente_viaje_bloque), (SELECT SUM(litros_bloque) FROM fact_viaje_combustible)")
    c["litros_puente_vs_viajes"] = round((lp or 0) - (lv or 0), 1)
    c["viajes_con_costo"] = q("SELECT COUNT(*) FROM fact_viaje_combustible WHERE costo_combustible IS NOT NULL")[0]
    c["viajes_sin_costo"] = q("SELECT COUNT(*) FROM fact_viaje_combustible WHERE costo_combustible IS NULL AND litros_asignados > 0")[0]
    c["costo_total"] = round(q("SELECT SUM(costo_combustible) FROM fact_viaje_combustible")[0] or 0)
    return c


